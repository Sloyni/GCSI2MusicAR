import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
// Import the exact module as ESM without requiring package.json in a Python app.
const code=await readFile(new URL("../web/audio.js",import.meta.url),"utf8");
const {AudioEngine}=await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const engine=new AudioEngine(()=>{});
let target;
engine.context={currentTime:0};
engine.master={gain:{setTargetAtTime(value){target=value;}}};
engine.setVolume(.7);
assert.equal(target,.7*1.3,"Le gain doit être le double de la version précédente (0.65)");
let released;
engine.voices.set("hand:1:index",{note:60});
engine.releaseVoice=(source,seconds)=>released={source,seconds};
engine.sustain=true;
engine.noteOff("hand:1:index",true);
assert.equal(released.source,"hand:1:index");
assert.equal(released.seconds,.065,"Sortir du piano doit couper immédiatement malgré le sustain");
released=null;engine.voices.set("key:a",{note:60});engine.noteOff("key:a");
assert.equal(released,null,"Le sustain clavier reste disponible");
engine.voices.set("guitar",{plucked:true});engine.noteOff("guitar",true);
assert.equal(released,null,"Une corde pincée doit résonner naturellement");
console.log("4 contrôles audio réussis : gain ×2, sortie immédiate, sustain clavier, corde naturelle.");
const pitchEngine=new AudioEngine(()=>{}),detunes=[];
pitchEngine.context={currentTime:4};
pitchEngine.voices.set("piano",{player:{detune:{setTargetAtTime(...args){detunes.push(args);}}}});
pitchEngine.voices.set("drum",{drum:true,player:{detune:{setTargetAtTime(){throw new Error("Une percussion ne doit pas suivre le pitch");}}}});
pitchEngine.configure({transpose:3,music_style:"electric",tone:.5});
pitchEngine.setPitch(1.5);
assert.equal(detunes.at(-1)[0],450,"Transpose + pitch doivent moduler les voix déjà actives");
assert.equal(detunes.at(-1)[2],.045,"Le pitch doit être lissé pour éviter les sauts");
pitchEngine.setPitch(0);assert.equal(detunes.at(-1)[0],300,"La perte de contrôle restaure la transposition seule");
console.log("Pitch : voix actives, transposition, lissage et percussions indépendantes vérifiés.");
const sampler=new AudioEngine(()=>{}),param=()=>({value:0,setValueAtTime(){},linearRampToValueAtTime(){},setTargetAtTime(){}});
const node=()=>({connect(){return this;},disconnect(){},gain:param(),frequency:param(),Q:param()});
sampler.context={state:"running",currentTime:0,createBufferSource(){return {...node(),playbackRate:param(),detune:param(),start(){}};},createBiquadFilter:node,createGain:node};
sampler.input=node();sampler.buffers.set(60,"C4");sampler.buffers.set(72,"C5");sampler.transpose=12;
sampler.noteOn(60,"test");
assert.equal(sampler.voices.get("test").player.buffer,"C5","La transposition doit choisir l’échantillon le plus proche de la note réellement entendue");
assert.equal(sampler.voices.get("test").player.playbackRate.value,1);
assert.equal(sampler.voices.get("test").player.detune.value,0);
const starts=[],fades=[];
sampler.context.currentTime=10;
sampler.context.createBufferSource=()=>({...node(),playbackRate:param(),detune:param(),start(time){starts.push(time);},stop(){}});
sampler.guitarBuffers.set(60,"guitar");
sampler.fade=(voice,release,when)=>fades.push({voice,when});
sampler.noteOn(60,"pick:1",.7,"guitar",{string:0,when:10.01,delay:.02});
sampler.noteOn(60,"pick:2",.7,"guitar",{string:1,when:10.01,delay:.045});
assert(Math.abs(starts[1]-starts[0]-.025)<1e-9,"Les attaques doivent conserver leurs intervalles dans un même paquet");
sampler.noteOn(60,"pick:3",.7,"guitar",{string:0,when:10.1});
assert.equal(fades.at(-1).when,10.1,"La corde précédente ne doit être étouffée qu’à l’instant de la nouvelle attaque");
sampler.context.state="running";
assert(!sampler.ready("guitar"),"Une banque incomplète doit être chargée avant de jouer");
assert(sampler.ready("drums"),"Les percussions sont jouables immédiatement si le contexte est actif");
console.log("Guitare : attaques espacées et étouffement à l’instant programmé vérifiés.");
